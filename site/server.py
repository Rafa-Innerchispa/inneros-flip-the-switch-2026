def check_tcp_port(host, port, timeout=0.8):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except Exception:
        return False

def check_http_url(url, timeout=1.0):
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "InnerOS-Check/1.0"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status == 200
    except Exception:
        return False

