class LiveOpsHandler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=BASE_DIR, **kwargs)

    def end_headers(self):
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Cache-Control", "no-cache, no-store, must-revalidate")
        self.send_header("Content-Security-Policy", "default-src 'self' 'unsafe-inline' https:; img-src 'self' data: https:; font-src 'self' https: data:;")
        super().end_headers()

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            index_path = os.path.join(BASE_DIR, "index.html")
            if os.path.exists(index_path):
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.end_headers()
                with open(index_path, "rb") as f:
                    self.wfile.write(f.read())
                return
            else:
                self.send_error(404, "index.html not found")
                return

        elif self.path == "/api/liveops/status":
            data = get_system_telemetry()
            payload = json.dumps(data, indent=2).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(payload)))
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(payload)
            return

        elif self.path == "/api/liveops/evidence":
            ev_path = os.path.join(DATA_DIR, "live_mattermost_evidence.json")
            if os.path.exists(ev_path):
                with open(ev_path, "r", encoding="utf-8") as f:
                    raw = json.load(f)
            else:
                raw = []
            payload = json.dumps(raw, indent=2).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(payload)))
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(payload)
            return

        elif self.path == "/api/liveops/tests":
            test_path = os.path.join(DATA_DIR, "e2e_results.json")
            if os.path.exists(test_path):
                with open(test_path, "r", encoding="utf-8") as f:
                    raw = json.load(f)
            else:
                raw = []
            payload = json.dumps(raw, indent=2).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(payload)))
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(payload)
            return

        else:
            return super().do_GET()

if __name__ == "__main__":
    socketserver.TCPServer.allow_reuse_address = True
